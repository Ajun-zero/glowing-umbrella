/**
 * 一个基础的Java文件示例
 * 文件名必须与公共类名一致，即 HelloWorld.java
 */
public class HelloWorld {

    /**
     * 主方法：程序的入口点
     * @param args 命令行参数（本例中未使用）
     */
    public static void main(String[] args) {
        // 向控制台输出一条问候信息
        System.out.println("Hello, World!");
        
        // 也可以输出其他内容
        System.out.println("这是一个基础的Java程序。");
    }
}
